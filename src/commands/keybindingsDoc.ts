/**
 * Renders `docs/keybindings.md` from the single source of truth.
 *
 * The default keymap lives in `keys.ts` (DEFAULT_BINDINGS + the region of each
 * command) and the labels in `builtin.ts`; a hand-written table in the README
 * drifted from both, which is why the table is generated now. The test next to
 * this file fails when the file on disk is stale, and `pnpm docs:keybindings`
 * regenerates it.
 *
 * `keys.ts` is pure (no imports), and `builtin.ts` registers its definitions at
 * module load, so both can be read from a node-environment test.
 */

import { allCommands } from "./registry";
import {
  DEFAULT_BINDINGS,
  KEY_REGIONS,
  defaultRegionsOf,
  keysOf,
  parseBinding,
  type KeyRegion,
} from "./keys";

/** A stable, platform-independent key label: `Cmd+Shift+A` (not the macOS glyphs). */
export function docKeyLabel(binding: string): string {
  const { mods, key } = parseBinding(binding);
  const name = (part: string) =>
    part === "Mod"
      ? "Cmd"
      : part === "Shift"
        ? "Shift"
        : part === "Alt"
          ? "Alt"
          : part === "Ctrl"
            ? "Ctrl"
            : part;
  const base = key.length === 1 ? key.toUpperCase() : key;
  return [...mods.map(name), base].join("+");
}

/** The English "when it applies" line per region; the Chinese hint stays in the app UI. */
const REGION_SCOPE: Record<KeyRegion, string> = {
  global: "Active whatever has focus: palette, saving, switching modes.",
  notes: "Active while the note editor has focus (the notes column of study mode counts).",
  reading:
    "Active while the reading pane has focus: PDF, web page, WeRead. Paging and the read-pane snapshot also fire from any region.",
  agent: "Active while the assistant panel has focus: input, transcript, history.",
  project:
    "Active in the project view. The editing keys of the notes region still work; project actions take precedence.",
  code: "Active while the code editor has focus. A separate world: `Cmd+S` saves the code file, `Cmd+Shift+O` opens a file by name. Only a few app-level commands are inherited.",
};

/** Commands that are deliberately unbound (documented in the README instead of a row). */
export const UNBOUND_BY_DESIGN: Record<string, string> = {
  "view.toggle-code-mode":
    "Code mode has no default shortcut (`Cmd+Shift+C` inserts a code block). Bind it in the `global` region.",
};

export function renderKeybindingsDoc(): string {
  const titles = new Map(allCommands().map((c) => [c.id, c.title]));
  const byRegion = new Map<KeyRegion, Array<{ keys: string[]; title: string; id: string }>>();
  for (const region of KEY_REGIONS) byRegion.set(region.id, []);
  for (const [id, value] of Object.entries(DEFAULT_BINDINGS)) {
    const keys = keysOf(value).map(docKeyLabel);
    if (keys.length === 0) continue;
    const title = titles.get(id) ?? id;
    for (const region of defaultRegionsOf(id)) {
      byRegion.get(region)?.push({ keys, title, id });
    }
  }

  const lines: string[] = [
    "# Default keybindings",
    "",
    "> macOS defaults, generated from `src/commands/keys.ts` — do not edit this file by hand,",
    "> run `pnpm docs:keybindings`. Every command can be rebound or unbound per region in",
    "> Settings → Hotkeys; the file is `<vault>/.bnote/keybindings.json`.",
    "> The command column is the UI label (the app ships Chinese copy).",
    "",
  ];

  for (const region of KEY_REGIONS) {
    const rows = (byRegion.get(region.id) ?? []).sort(
      (a, b) => a.keys[0]!.localeCompare(b.keys[0]!) || a.id.localeCompare(b.id),
    );
    if (rows.length === 0) continue;
    lines.push(`## ${region.label} (\`${region.id}\`)`, "", REGION_SCOPE[region.id], "");
    lines.push("| Key | Command |", "| --- | --- |");
    for (const row of rows) {
      const label = row.title === row.id ? `\`${row.id}\`` : `${row.title} — \`${row.id}\``;
      lines.push(`| ${row.keys.map((k) => `\`${k}\``).join(" / ")} | ${label} |`);
    }
    lines.push("");
  }

  const unbound = Object.entries(UNBOUND_BY_DESIGN).filter(([id]) => titles.has(id));
  if (unbound.length > 0) {
    lines.push("## Unbound on purpose", "");
    for (const [id, why] of unbound) lines.push(`- \`${id}\`: ${why}`);
    lines.push("");
  }
  return lines.join("\n");
}
