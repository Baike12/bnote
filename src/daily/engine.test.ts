/**
 * Engine level integration test: a real EditorState plus the real toggleTodo
 * produce the transactions, they drive the same "transaction -> intent -> apply"
 * pipeline as extension.ts, and an in-memory IO carries the daily note and the
 * source file. It locks the behaviour (two way sync on check, hierarchy of child
 * todos, auto sync and aggregation, chronological order, unlinking rules).
 */

const VAULT = "/vault";
const DAILY = "/vault/Daily/2026-09-23.md";

function makeDocView(doc: string, path: string, cursors: number[] = [0]) {
  let state = EditorState.create({
    doc,
    extensions: [docPathField, EditorState.allowMultipleSelections.of(true)],
    selection: EditorSelection.create(cursors.map((c) => EditorSelection.cursor(c))),
  });
  state = state.update({ effects: setDocPath.of(path) }).state;
  const transactions: Transaction[] = [];
  const view = {
    get state() {
      return state;
    },
    get dom() {
      return { isConnected: true };
    },
    dispatch: (spec: TransactionSpec) => {
      const tr = state.update(spec);
      if (tr.docChanged) transactions.push(tr);
      state = tr.state;
    },
  };
  return { view: view as unknown as EditorView, transactions };
}

function memIO() {
  const files = new Map<string, string>();
  return {
    files,
    io: {
      async readFile(p: string) {
        return files.has(p) ? (files.get(p) as string) : null;
      },
      async writeFile(p: string, c: string) {
        files.set(p, c);
      },
      async readDir(relPath: string) {
        const prefix = `${VAULT}/${relPath}/`;
        return [...files.keys()]
          .filter((k) => k.startsWith(prefix) && !k.slice(prefix.length).includes("/"))
          .map((k) => k.slice(prefix.length));
      },
    } as DailyIO,
  };
}

function deps(
  io: DailyIO,
  toasts: string[] = [],
  templatePath: () => string | null = () => null,
): DailyDeps {
  return {
    io,
    vaultRoot: () => VAULT,
    today: () => "2026-09-23",
    toast: (m) => toasts.push(m),
    templatePath,
  };
}

function makeLink(patch: Partial<DailyLink>): DailyLink {
  return {
    id: "l1",
    kind: "copied",
    day: "2026-09-23",
    srcPath: "/vault/p.md",
    dailyPath: DAILY,
    text: "任务甲",
    srcLine: 1,
    dailyLine: 3,
    ...patch,
  };
}

/** The same transaction -> intent pipeline as extension.ts (it swallows the accumulated transactions). */
function drainIntents(transactions: Transaction[], store: LinkStore, path: string): Intent[] {
  const fileLinks = store.forFile(path);
  const out: Intent[] = [];
  for (const tr of transactions.splice(0)) {
    if (!tr.docChanged) continue;
    if (tr.isUserEvent("input.bnote-daily-sync")) continue;
    const allow =
      !isDailyPath(path) && !tr.isUserEvent("input.paste") && !tr.isUserEvent("input.drop");
    tr.changes.iterChangedRanges((fromA, toA, fromB, toB) =>
      out.push(
        ...intentsForRange(
          tr.startState.doc,
          tr.state.doc,
          fromA,
          toA,
          fromB,
          toB,
          fileLinks,
          allow,
        ),
      ),
    );
  }
  return out;
}

async function sync(
  view: EditorView,
  path: string,
  transactions: Transaction[],
  io: DailyIO,
  store: LinkStore,
): Promise<void> {
  const intents = drainIntents(transactions, store, path);
  if (intents.length) await applyIntents(view, path, intents, deps(io), store);
}

